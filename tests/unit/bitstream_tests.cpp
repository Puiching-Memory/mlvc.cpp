// One-byte-at-a-time streambuf with in_avail() == 0 to verify FIFO/pipe reads.
class OneByteStreambuf final : public std::streambuf {
public:
    explicit OneByteStreambuf(const std::vector<std::byte>& data) : data_(data) {}

protected:
    int_type underflow() override
    {
        if (pos_ >= data_.size())
            return traits_type::eof();
        current_ = static_cast<char>(data_[pos_]);
        setg(&current_, &current_, &current_ + 1);
        return traits_type::to_int_type(current_);
    }

    int_type uflow() override
    {
        const int_type ch = underflow();
        if (ch != traits_type::eof()) {
            ++pos_;
            setg(nullptr, nullptr, nullptr);
        }
        return ch;
    }

private:
    const std::vector<std::byte>& data_;
    std::size_t pos_ = 0;
    char current_ = 0;
};


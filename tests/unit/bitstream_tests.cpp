void test_access_unit_reader_and_validation()
{
    const auto payload = bytes({0xAA, 0x00, 0x00, 0x01, 0xBB});
    const auto f0 = OwningFrame::i_frame(payload, 640, 368, 21)
                        .with_crop({0, 0, 0, 8}, false);
    const auto f1 = f0.as_p_frame(1, 0);
    const auto f2 = OwningFrame::i_frame(payload, 640, 368, 25)
                        .with_crop({0, 8, 0, 0}, true);

    std::vector<std::byte> stream_bytes;
    {
        mlvc::BitstreamEncoder encoder;
        std::ostringstream out(std::ios::binary);
        mlvc::write_access_unit(out, encoder.encode(f0.view()));
        mlvc::write_access_unit(out, encoder.encode(f1.view()));
        mlvc::write_access_unit(out, encoder.encode(f2.view()));
        const std::string raw = out.str();
        stream_bytes.resize(raw.size());
        for (std::size_t i = 0; i < raw.size(); ++i)
            stream_bytes[i] = static_cast<std::byte>(static_cast<unsigned char>(raw[i]));
    }

    OneByteStreambuf slow_buf(stream_bytes);
    std::istream slow_stream(&slow_buf);
    mlvc::AccessUnitReader reader(slow_stream);
    mlvc::BitstreamDecoder decoder;

    std::vector<std::byte> au;
    require(reader.read(au), "expected AU 0");
    const auto d0 = decoder.decode(au);
    expect_frame_data_equal(d0, f0.view(), "slow stream AU 0");
    require(d0.display_width() == 640 && d0.display_height() == 360,
            "unexpected AU 0 display dimensions");

    require(reader.read(au), "expected AU 1");
    expect_frame_data_equal(decoder.decode(au), f1.view(), "slow stream AU 1");

    require(reader.read(au), "expected AU 2");
    const auto d2 = decoder.decode(au);
    expect_frame_data_equal(d2, f2.view(), "slow stream AU 2");
    require(d2.display_width() == 368 && d2.display_height() == 632,
            "unexpected transposed display dimensions");

    require(!reader.read(au), "expected clean EOF after AU 2");

    // Trailing SPS without a VCL frame NALU must raise kPartialAccessUnit.
    const auto partial_sps =
        bytes({0x00, 0x00, 0x00, 0x01, 0x42, 0x01, 0x00, 0x01, 0x85, 0x00, 0x2D, 0x01, 0xC0});
    OneByteStreambuf partial_buf(partial_sps);
    std::istream partial_stream(&partial_buf);
    mlvc::AccessUnitReader partial_reader(partial_stream);
    bool partial_threw = false;
    try {
        static_cast<void>(partial_reader.read(au));
    } catch (const mlvc::BitstreamError& err) {
        partial_threw = (err.code() == mlvc::BitstreamErrorCode::kPartialAccessUnit);
    }
    require(partial_threw, "partial non-VCL AU at EOF must throw kPartialAccessUnit");

    // Encoder guards.
    mlvc::BitstreamEncoder guard_encoder;
    bool missing_sps = false;
    try {
        static_cast<void>(guard_encoder.encode(f1.view()));
    } catch (const mlvc::BitstreamError& err) {
        missing_sps = (err.code() == mlvc::BitstreamErrorCode::kMissingSps);
    }
    require(missing_sps, "encoding P-frame before I-frame must throw kMissingSps");
}

